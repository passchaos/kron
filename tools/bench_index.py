#!/usr/bin/env python3
"""Generate or verify the benchmark evidence index.

The index is intentionally derived from directory names, README headings and
manifest presence. It does not parse measurement results; those stay in each
experiment directory with their own identity.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SECTIONS = (
    ("Core benchmark evidence", ROOT / "bench/evidence", ""),
    ("C++ reference evidence", ROOT / "bench/cpp_reference/evidence", "../cpp_reference/evidence"),
)
INDEX = ROOT / "bench/evidence/INDEX.md"


def first_heading(path: pathlib.Path) -> str | None:
    if not path.is_file():
        return None
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(r"^#\s+(.+?)\s*$", line)
        if match:
            return match.group(1).strip()
    return None


def render() -> str:
    lines = [
        "# Benchmark evidence index",
        "",
        "Generated by `python3 tools/bench_index.py`. Do not edit by hand;",
        "add a `README.md` and `manifest.json` in the experiment directory instead.",
        "",
        "Missing README entries are kept visible so the gap does not disappear.",
        "",
    ]
    for title, directory, prefix in SECTIONS:
        lines.extend((f"## {title}", "", "| Evidence | Summary | README | Manifest |", "| --- | --- | --- | --- |"))
        if not directory.is_dir():
            lines.append(f"| `{prefix}` | missing directory | - | - |")
            lines.append("")
            continue
        for experiment in sorted((entry for entry in directory.iterdir() if entry.is_dir()), key=lambda entry: entry.name):
            readme = experiment / "README.md"
            manifest = experiment / "manifest.json"
            summary = first_heading(readme) or "**(missing README)**"
            summary = summary.replace("|", "\\|")
            base = f"{prefix}/{experiment.name}" if prefix else experiment.name
            readme_link = f"[README]({base}/README.md)" if readme.is_file() else "-"
            manifest_link = f"[manifest]({base}/manifest.json)" if manifest.is_file() else "-"
            lines.append(f"| `{experiment.name}` | {summary} | {readme_link} | {manifest_link} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if INDEX.md is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        actual = INDEX.read_text(encoding="utf-8") if INDEX.is_file() else ""
        if actual != expected:
            print(f"{INDEX.relative_to(ROOT)} is stale; run python3 tools/bench_index.py", file=sys.stderr)
            return 1
        print(f"{INDEX.relative_to(ROOT)} is current")
        return 0
    INDEX.write_text(expected, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
